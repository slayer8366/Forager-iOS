"""Writes MsunReference.kt, the C reference's values as commonTest data, from build-ref.sh's outputs (step 2b).

    python3 -I tools/msun-ref/gen-kotlin.py <build-ref outdir> > \
        brouter/src/commonTest/kotlin/com/zynergylabs/forager/brouter/msun/MsunReference.kt

The jvmTest MsunReferenceCommittedTest re-reads the same outputs, built fresh by every jvmTest run, and fails unless the
committed values equal them line for line; so the committed copy cannot drift from bionic's C unnoticed.
"""
import sys

out = sys.argv[1]
cos = [l.split() for l in open(out + "/msun-cos.txt") if not l.startswith("#")]
edges = [l.split() for l in open(out + "/msun-edges.txt")]
assert len(cos) == 1800 and [int(r[0]) for r in cos] == list(range(1800)), "msun-cos.txt is not rows 0 to 1799"


def unsupported(x):
    # e_rem_pio2.c at 06356e41: finite |x| whose high word is not below 0x413921fb goes to __kernel_rem_pio2.
    ix = (int(x, 16) >> 32) & 0x7FFFFFFF
    return 0x413921FB <= ix < 0x7FF00000


def raw(name, lines):
    body = "\n".join("    " + l for l in lines)
    return 'internal val %s: String = """\n%s\n""".trimIndent()\n' % (name, body)


print("// Generated by tools/msun-ref/gen-kotlin.py from tools/msun-ref/build-ref.sh's outputs: bionic's msun at")
print("// android-17.0.0_r1 (06356e41), built with Android's flags. Do not edit; regenerate. jvmTest's")
print("// MsunReferenceCommittedTest fails unless every line equals a fresh build's.")
print("package com.zynergylabs.forager.brouter.msun")
print()
print("/** SHA-256 of at2.c's output over the 299,974 pairs (research/android-math 736a4c1, q7/results/sha256-and-wc.txt). */")
print('internal const val MSUN_ATAN2_PAIRS_SHA256: String = "466fb82d7bccec4d017c61fa86ad4d0d467c3f3281e5cc646ff818d1fbd43dfa"')
print()
print("/** tab.c's rows: row, lat bits, cos bits (hex). Two strings, each under the JVM's 64 KiB constant limit. */")
print(raw("MSUN_COS_ROWS_A", [" ".join(r) for r in cos[:900]]))
print(raw("MSUN_COS_ROWS_B", [" ".join(r) for r in cos[900:]]))
print("/** edges.c's lines: \"c x result\" or \"a y x result\" (hex); \"u\" in place of \"c\" marks k_rem_pio2.c's range. */")
lines = []
for e in edges:
    if e[0] == "c" and unsupported(e[1]):
        e = ["u"] + e[1:]
    lines.append(" ".join(e))
print(raw("MSUN_EDGES", lines), end="")
